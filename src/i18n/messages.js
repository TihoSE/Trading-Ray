export function translate(locale, key, vars) {
  const table = messages[locale] ?? messages.en
  const template = table[key] ?? messages.en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''))
}
